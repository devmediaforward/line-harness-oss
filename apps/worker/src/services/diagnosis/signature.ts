// =============================================================================
// タグ集合シグネチャ — engine.ts / validate.ts で共有(重複定義禁止)
//
// keyTags 内のインデックス番号を昇順ソートして "," で連結する。
// タグ名の内容(スペース・記号)に一切依存しないため、名前を区切り文字で連結する
// 方式にありがちな衝突(例: {"a","b"} と {"a b"} が同じ文字列になる)が起きない。
// 前提: key の要素は keyTags に含まれること(未知タグは一律 -1 になり互いに区別
// できないため、呼び出し側が事前に keyTags 包含を検査・除外してから使う。
// engine はフィルタ済み集合を渡し、validate は未知タグを別途エラーにする)。
// =============================================================================

/**
 * key(タグ名の配列)を keyTags 内のインデックス集合として正規化したシグネチャ。
 * 順不同一致に使う。keyTags に無いタグは -1(呼び出し側で別途 keyTags 包含を検査)。
 */
export function keyTagSignature(key: string[], keyTags: string[]): string {
  const index = new Map(keyTags.map((tag, i) => [tag, i] as const));
  return key
    .map((tag) => index.get(tag) ?? -1)
    .sort((a, b) => a - b)
    .join(',');
}
